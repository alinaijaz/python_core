# For loop
for i in range(1, 6):
    print(i)

# While loop 
i = 1
while i <= 5:
    print(i)
    i += 1

# Break
for i in range(1, 6):
    if i == 3:
        break
    print(i)
# Continue
for i in range(1, 6):
    if i == 3:
        break
    print(i)
# Else with loop
for i in range(3):
    print(i)
else:
    print("Loop completed")                   

